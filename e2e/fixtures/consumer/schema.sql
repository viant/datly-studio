CREATE TABLE IF NOT EXISTS customers(id INTEGER PRIMARY KEY AUTOINCREMENT,tenant TEXT NOT NULL,name TEXT NOT NULL,active INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS orders(id INTEGER PRIMARY KEY AUTOINCREMENT,customer_id INTEGER NOT NULL REFERENCES customers(id),amount NUMERIC NOT NULL,status TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS order_items(id INTEGER PRIMARY KEY AUTOINCREMENT,order_id INTEGER NOT NULL REFERENCES orders(id),product TEXT NOT NULL,quantity INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS ui_feature_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_role_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_both_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_policy_edit_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_complex_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL,state TEXT NOT NULL,score INTEGER NOT NULL,region TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS ui_complex_contact(id INTEGER PRIMARY KEY,record_id INTEGER NOT NULL REFERENCES ui_complex_records(id),label TEXT NOT NULL,detail TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS ui_complex_order(id INTEGER PRIMARY KEY,record_id INTEGER NOT NULL REFERENCES ui_complex_records(id),amount INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS ui_complex_note(id INTEGER PRIMARY KEY,record_id INTEGER NOT NULL REFERENCES ui_complex_records(id),message TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_wildcard_exposure_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_wildcard_role_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_entity_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_namespace_admin_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS ui_custom_predicate_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS predicate_presence_orders(id INTEGER PRIMARY KEY,customer_id INTEGER NOT NULL,status TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS predicate_presence_exclusions(id INTEGER PRIMARY KEY,customer_id INTEGER NOT NULL,active INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS ui_cube_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL,region TEXT NOT NULL,channel TEXT NOT NULL,amount INTEGER NOT NULL);

CREATE TABLE IF NOT EXISTS ui_compose_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL,region TEXT NOT NULL,channel TEXT NOT NULL,amount INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS ui_catalog_records(id INTEGER PRIMARY KEY,name TEXT NOT NULL);
